public class forLoop {
    public static void main(String[] args) {
        for(int i =1; i <=10; i++){  // 11 times execution
        System.out.println(i);  // 10 times execution
        }

        //while
        int i = 0;
        while(i <=10){
        System.out.println(i);
        i++;
        }
    }
}
